
'use client';

import { useState } from 'react';
import { Download, Loader2 } from 'lucide-react';

interface DownloadTransactionPdfProps {
  reference: string;
  amount: string;
  currency: string;
  description: string;
  accountName: string;
  accountNumber: string;
  transactionType: string;
  status: string;
  createdAt: string;
}

export function DownloadTransactionPdf({
  reference,
  amount,
  currency,
  description,
  accountName,
  accountNumber,
  transactionType,
  status,
  createdAt,
}: DownloadTransactionPdfProps) {
  const [loading, setLoading] = useState(false);

  const downloadPDF = async () => {
    try {
      setLoading(true);

      const { jsPDF } = await import('jspdf');

      const pdf = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4',
      });

      const pageWidth = pdf.internal.pageSize.getWidth();
      const margin = 20;
      const contentWidth = pageWidth - margin * 2;

      const formattedAmount = `${currency} ${Number(amount).toLocaleString(
        'en-US',
        {
          minimumFractionDigits: 2,
          maximumFractionDigits: 2,
        }
      )}`;

      const normalizedStatus = status.toUpperCase();

      // Header
      pdf.setFillColor(36, 30, 70);
      pdf.rect(0, 0, pageWidth, 42, 'F');

      pdf.setTextColor(255, 255, 255);
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(19);
      pdf.text('APEX VAULT', margin, 19);

      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(9);
      pdf.text('PRIVATE WEALTH - DEMO APPLICATION', margin, 26);

      pdf.setFontSize(10);
      pdf.text('TRANSACTION RECEIPT', pageWidth - margin, 19, {
        align: 'right',
      });

      // Demo notice
      pdf.setFillColor(255, 244, 214);
      pdf.rect(margin, 50, contentWidth, 13, 'F');

      pdf.setTextColor(125, 75, 0);
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(9);
      pdf.text(
        'DEMO DOCUMENT - NOT A REAL BANK STATEMENT OR PROOF OF PAYMENT',
        pageWidth / 2,
        58,
        { align: 'center' }
      );

      // Amount
      pdf.setTextColor(100, 100, 100);
      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(10);
      pdf.text('TRANSACTION AMOUNT', pageWidth / 2, 82, {
        align: 'center',
      });

      pdf.setTextColor(25, 25, 35);
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(25);
      pdf.text(formattedAmount, pageWidth / 2, 95, {
        align: 'center',
      });

      // Status
      const statusColor =
        status.toLowerCase() === 'pending'
          ? [180, 115, 0]
          : status.toLowerCase() === 'rejected' ||
              status.toLowerCase() === 'failed'
            ? [185, 45, 45]
            : status.toLowerCase() === 'reversed'
              ? [110, 75, 160]
              : [20, 130, 85];

      pdf.setFillColor(
        statusColor[0],
        statusColor[1],
        statusColor[2]
      );
      pdf.roundedRect(pageWidth / 2 - 19, 103, 38, 9, 2, 2, 'F');

      pdf.setTextColor(255, 255, 255);
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(8);
      pdf.text(normalizedStatus, pageWidth / 2, 109, {
        align: 'center',
      });

      // Divider
      pdf.setDrawColor(220, 220, 225);
      pdf.line(margin, 123, pageWidth - margin, 123);

      // Transaction details
      pdf.setTextColor(35, 35, 45);
      pdf.setFont('helvetica', 'bold');
      pdf.setFontSize(12);
      pdf.text('Transaction Information', margin, 137);

      const details: [string, string][] = [
        ['Transaction Reference', reference],
        ['Transaction Type', transactionType],
        ['Description', description],
        ['Account Name', accountName],
        ['Account Number', accountNumber],
        ['Currency', currency],
        ['Transaction Date', createdAt],
        ['Transaction Status', normalizedStatus],
      ];

      let y = 151;

      for (const [label, value] of details) {
        pdf.setFont('helvetica', 'normal');
        pdf.setFontSize(9);
        pdf.setTextColor(110, 110, 120);
        pdf.text(label, margin, y);

        pdf.setFont('helvetica', 'bold');
        pdf.setTextColor(35, 35, 45);

        const lines = pdf.splitTextToSize(
          value || 'N/A',
          contentWidth - 55
        );

        pdf.text(lines, margin + 55, y);

        y += Math.max(11, lines.length * 5 + 3);

        pdf.setDrawColor(235, 235, 238);
        pdf.line(margin, y - 4, pageWidth - margin, y - 4);
      }

      // Footer
      const footerY = Math.max(y + 10, 250);

      pdf.setTextColor(100, 100, 110);
      pdf.setFont('helvetica', 'normal');
      pdf.setFontSize(8);

      pdf.text(
        'This receipt was generated by the Apex Vault demo application.',
        pageWidth / 2,
        footerY,
        { align: 'center' }
      );

      pdf.setFont('helvetica', 'bold');
      pdf.text(
        'DEMO ONLY - NOT VALID FOR FINANCIAL VERIFICATION',
        pageWidth / 2,
        footerY + 7,
        { align: 'center' }
      );

      const safeReference = reference.replace(/[^a-zA-Z0-9-]/g, '');
      pdf.save(`Apex-Vault-Demo-Receipt-${safeReference}.pdf`);
    } catch (error) {
      console.error('PDF generation failed:', error);
      alert('Unable to generate the PDF. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <button
      type="button"
      onClick={downloadPDF}
      disabled={loading}
      className="inline-flex items-center justify-center gap-2 rounded-lg bg-violet-600 px-4 py-2.5 text-sm font-semibold text-white transition hover:bg-violet-700 disabled:cursor-not-allowed disabled:opacity-60"
    >
      {loading ? (
        <Loader2 size={17} className="animate-spin" />
      ) : (
        <Download size={17} />
      )}

      {loading ? 'Preparing PDF...' : 'Download PDF'}
    </button>
  );
}
